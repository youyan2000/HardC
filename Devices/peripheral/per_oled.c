// -------- 定位 --------
static void oled_set_pos(PerOled *me, uint8_t x, uint8_t y) {
  oled_write_byte(me, 0xB0 + y, OLED_CMD);
  oled_write_byte(me, ((x & 0xF0) >> 4) | 0x10, OLED_CMD);
  oled_write_byte(me, x & 0x0F, OLED_CMD);
}

// -------- 字符 --------
void per_oled_show_char(PerOled *me, uint8_t x, uint8_t y, uint8_t chr, uint8_t size) {
  if (x > 120)
    return;
  uint8_t c = chr - ' ';
  (void) size;  // 仅支持 6px 字体, f8x16 已移除以节省 flash
  oled_set_pos(me, x, y);
  for (uint8_t i = 0; i < 6; i++) {
    oled_write_byte(me, f6x8[c][i], OLED_DATA);
  }
}

void per_oled_show_string(PerOled *me, uint8_t x, uint8_t y, const char *str, uint8_t len, uint8_t size) {
  for (uint8_t j = 0; j < len; j++) {
    per_oled_show_char(me, x, y, str[j], size);
    x += size;
    if (x > 120)
      break;
  }
}

// -------- 数字 --------
static uint32_t oled_pow(uint8_t m, uint8_t n) {
  uint32_t r = 1;
  while (n != 0) {
    r *= m;
    n--;
  }
  return r;
}

void per_oled_show_num(PerOled *me, uint8_t x, uint8_t y, uint32_t num, uint8_t len, uint8_t size) {
  for (uint8_t t = 0; t < len; t++) {
    uint8_t v = (num / oled_pow(10, len - t - 1)) % 10;
    per_oled_show_char(me, x + size * t, y, v + '0', size);
  }
}

// 定点小数格式化: 负数 + 整数部分 + 小数点 + 小数部分 (补前导零) → 字符串
static uint8_t oled_fmt_fnum(float num, uint8_t plen, char *str) {
  uint32_t scale = 1;
  uint8_t neg = 0;
  uint32_t v, ipart, fpart;
  char ibuf[12], fbuf[12];
  uint8_t ip = 0, fp = 0, pos = 0;

  if (num < 0.0f) {
    neg = 1;
    num = -num;
  }
  for (uint8_t i = 0; i < plen; i++) {
    scale *= 10;
  }
  v = (uint32_t) (num * (float) scale + 0.5f);
  ipart = v / scale;
  fpart = v % scale;

  // 整数部分 (倒序入栈)
  do {
    ibuf[ip++] = (char) ('0' + ipart % 10);
    ipart /= 10;
  } while (ipart != 0);
  // 小数部分 (倒序入栈 + 补前导零)
  do {
    fbuf[fp++] = (char) ('0' + fpart % 10);
    fpart /= 10;
  } while (fpart != 0);
  while (fp < plen) {
    fbuf[fp++] = '0';
  }

  if (neg) {
    str[pos++] = '-';
  }
  while (ip != 0) {
    str[pos++] = ibuf[--ip];
  }
  if (plen != 0) {
    str[pos++] = '.';
    while (fp != 0) {
      str[pos++] = fbuf[--fp];
    }
  }
  str[pos] = '\0';
  return pos;
}

void per_oled_show_fnum(PerOled *me, uint8_t x, uint8_t y, float num, uint8_t len, uint8_t plen, uint8_t size) {
  char str[16];
  uint8_t n = oled_fmt_fnum(num, plen, str);
  (void) len;  // 按实际格式串长度输出
  for (uint8_t i = 0; i < n; i++) {
    per_oled_show_char(me, x, y, (uint8_t) str[i], size);
    x += size;
    if (x > 120)
      break;
  }
}
