// OLED (SSD1306) 外设 — 3 线软件 SPI bit-bang 实现
// 迁移自 Devices/sensor/oled.c, 引脚改走 BspGpioPin (bsp_gpio_write)

#include "per_oled.h"
#include "bsp_delay.h"
#include <string.h>

// -------- 底层: 3 线软件 SPI 写 1 字节 --------

// 写 1 字节: 第 1 bit = cmd/data, 后 8 bit = data
static void oled_write_byte(PerOled *me, uint8_t dat, uint8_t cmd) {
  // bit 0: cmd/data
  bsp_gpio_write(&me->scl, false);
  bsp_gpio_write(&me->sda, cmd ? true : false);
  bsp_gpio_write(&me->scl, true);
  // bit 1-8: data
  for (uint8_t i = 0; i < 8; i++) {
    bsp_gpio_write(&me->scl, false);
    bsp_gpio_write(&me->sda, (dat & 0x80) ? true : false);
    bsp_gpio_write(&me->scl, true);
    dat <<= 1;
  }
}

// -------- 初始化 / 反初始化 --------

// 初始化: 配 3 脚输出 → 复位时序 → 命令序列 → 清屏
void per_oled_init(PerOled *me, const char *name, BspGpioPin scl, BspGpioPin sda, BspGpioPin res, uint8_t *buf,
                   uint16_t buf_size) {
  me->name = name;
  me->scl = scl;
  me->sda = sda;
  me->res = res;
  me->buf = buf;
  me->buf_size = buf_size;
  if (me->buf == NULL || me->buf_size < OLED_BUF_SIZE) {
    me->inited = 0;
    return;
  }
  bsp_gpio_cfg_output(&me->scl);
  bsp_gpio_cfg_output(&me->sda);
  bsp_gpio_cfg_output(&me->res);

  // 硬件复位 (匹配工作版时序: 50ms LOW + 500ms HIGH)
  bsp_gpio_write(&me->res, false);
  Delay_ms(50);
  bsp_gpio_write(&me->res, true);
  Delay_ms(500);

  const uint8_t cmds[] = {0xAE, 0x00, 0x10, 0x40, 0x81, 0xCF, 0xA1, 0xC8, 0xA6, 0xA8, 0x3F, 0xD3, 0x00, 0xD5,
                          0x80, 0xD9, 0xF1, 0xDA, 0x12, 0xDB, 0x40, 0x20, 0x02, 0x8D, 0x14, 0xA4, 0xA6, 0xAF};
  for (uint8_t i = 0; i < sizeof(cmds); i++) {
    oled_write_byte(me, cmds[i], OLED_CMD);
  }
  per_oled_clear(me);
  me->inited = 1;
}

// 反初始化: 关显示 → 清标志
void per_oled_deinit(PerOled *me) {
  per_oled_off(me);
  me->inited = 0;
  me->buf = NULL;
  me->buf_size = 0;
}

// -------- 显存操作 --------

// 清显存 + 上屏
void per_oled_clear(PerOled *me) {
  memset(me->buf, 0, me->buf_size);
  per_oled_refresh(me);
}

// 整屏刷新: buf[页*128+列] → SSD1306 GDDRAM
void per_oled_refresh(PerOled *me) {
  for (uint8_t p = 0; p < 8; p++) {
    oled_write_byte(me, 0xB0 + p, OLED_CMD);
    oled_write_byte(me, 0x00, OLED_CMD);
    oled_write_byte(me, 0x10, OLED_CMD);
    for (uint8_t c = 0; c < 128; c++) {
      oled_write_byte(me, me->buf[p * 128 + c], OLED_DATA);
    }
  }
}

// 显示开关
void per_oled_on(PerOled *me) {
  oled_write_byte(me, 0x8D, OLED_CMD);
  oled_write_byte(me, 0x14, OLED_CMD);
  oled_write_byte(me, 0xAF, OLED_CMD);
}

void per_oled_off(PerOled *me) {
  oled_write_byte(me, 0x8D, OLED_CMD);
  oled_write_byte(me, 0x10, OLED_CMD);
  oled_write_byte(me, 0xAF, OLED_CMD);
}

// 画点/清点: 改显存 (页主序 buf[(y/8)*128 + x])
void per_oled_draw_point(PerOled *me, uint8_t x, uint8_t y) {
  if (x < 128 && y < 64) {
    me->buf[(y / 8) * 128 + x] |= (uint8_t) (1 << (y % 8));
  }
}

void per_oled_clear_point(PerOled *me, uint8_t x, uint8_t y) {
  if (x < 128 && y < 64) {
    me->buf[(y / 8) * 128 + x] &= (uint8_t) ~(1 << (y % 8));
  }
}

