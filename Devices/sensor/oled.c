// -------- 定位 --------
static void oled_set_pos(uint8_t x, uint8_t y) {
 oled_write_byte(0xB0 + y, OLED_CMD);
 oled_write_byte(((x & 0xF0) >> 4) | 0x10, OLED_CMD);
 oled_write_byte(x & 0x0F, OLED_CMD);
}

// -------- 字符 --------
void oled_show_char(uint8_t x, uint8_t y, uint8_t chr, uint8_t size) {
 if (x > 120) return;
 uint8_t c = chr - ' ';
 (void)size;  // 仅支持 6px 字体, f8x16 已移除以节省 flash
 oled_set_pos(x, y);
 for (uint8_t i = 0; i < 6; i++)
  oled_write_byte(f6x8[c][i], OLED_DATA);
}

void oled_show_string(uint8_t x, uint8_t y, const char *str, uint8_t len, uint8_t size) {
 for (uint8_t j = 0; j < len; j++) {
  oled_show_char(x, y, str[j], size);
  x += size;
  if (x > 120) break;
 }
}

// -------- 数字 --------
static uint32_t oled_pow(uint8_t m, uint8_t n) {
 uint32_t r = 1;
 while (n--) r *= m;
 return r;
}

void oled_show_num(uint8_t x, uint8_t y, uint32_t num, uint8_t len, uint8_t size) {
 for (uint8_t t = 0; t < len; t++) {
  uint8_t v = (num / oled_pow(10, len - t - 1)) % 10;
  oled_show_char(x + size * t, y, v + '0', size);
 }
}
