// 显存 (全局, 类似 HAL 外设句柄的静态性)
static uint8_t gram[128][8];

// 写 1 字节, 3 线 SPI: 第 1 bit = cmd/data, 后 8 bit = data
void oled_write_byte(uint8_t dat, uint8_t cmd) {
 // bit 0: cmd/data
 HAL_GPIO_WritePin(SPI_SCL_GPIO_Port, SPI_SCL_Pin, GPIO_PIN_RESET);
 HAL_GPIO_WritePin(SPI_MOSI_GPIO_Port, SPI_MOSI_Pin,
          cmd ? GPIO_PIN_SET : GPIO_PIN_RESET);
 HAL_GPIO_WritePin(SPI_SCL_GPIO_Port, SPI_SCL_Pin, GPIO_PIN_SET);
 // bit 1-8: data
 for (uint8_t i = 0; i < 8; i++) {
  HAL_GPIO_WritePin(SPI_SCL_GPIO_Port, SPI_SCL_Pin, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(SPI_MOSI_GPIO_Port, SPI_MOSI_Pin,
           (dat & 0x80) ? GPIO_PIN_SET : GPIO_PIN_RESET);
  HAL_GPIO_WritePin(SPI_SCL_GPIO_Port, SPI_SCL_Pin, GPIO_PIN_SET);
  dat <<= 1;
 }
}

void oled_init(void) {
 // 硬件复位 (匹配工作版时序: 50ms LOW + 500ms HIGH)
 HAL_GPIO_WritePin(OLED_RES_GPIO_Port, OLED_RES_Pin, GPIO_PIN_RESET);
 Delay_ms(50);
 HAL_GPIO_WritePin(OLED_RES_GPIO_Port, OLED_RES_Pin, GPIO_PIN_SET);
 Delay_ms(500);

 const uint8_t cmds[] = {
  0xAE, 0x00, 0x10, 0x40, 0x81, 0xCF, 0xA1, 0xC8, 0xA6,
  0xA8, 0x3F, 0xD3, 0x00, 0xD5, 0x80, 0xD9, 0xF1, 0xDA,
  0x12, 0xDB, 0x40, 0x20, 0x02, 0x8D, 0x14, 0xA4, 0xA6, 0xAF
 };
 for (uint8_t i = 0; i < sizeof(cmds); i++) {
  oled_write_byte(cmds[i], OLED_CMD);
 }
 oled_clear();
}

void oled_clear(void) {
 memset(gram, 0, sizeof(gram));
 oled_refresh();
}

void oled_refresh(void) {
 for (uint8_t p = 0; p < 8; p++) {
  oled_write_byte(0xB0 + p, OLED_CMD);
  oled_write_byte(0x00, OLED_CMD);
  oled_write_byte(0x10, OLED_CMD);
  for (uint8_t c = 0; c < 128; c++)
   oled_write_byte(gram[c][p], OLED_DATA);
 }
}

void oled_on(void) {
 oled_write_byte(0x8D, OLED_CMD);
 oled_write_byte(0x14, OLED_CMD);
 oled_write_byte(0xAF, OLED_CMD);
}

void oled_off(void) {
 oled_write_byte(0x8D, OLED_CMD);
 oled_write_byte(0x10, OLED_CMD);
 oled_write_byte(0xAF, OLED_CMD);
}

void oled_draw_point(uint8_t x, uint8_t y) {
 if (x < 128 && y < 64)
  gram[x][y / 8] |= (1 << (y % 8));
}

void oled_clear_point(uint8_t x, uint8_t y) {
 if (x < 128 && y < 64)
  gram[x][y / 8] &= ~(1 << (y % 8));
}

